def get_language_config(lang_code: str) -> Dict[str, Any]:
    code = (lang_code or "ta").lower().strip()
    if code.startswith("te"):
        return LANGUAGES["te"]
    return LANGUAGES["ta"]


def detect_language_switch_request(user_text: str, current_lang: str) -> str:
    """
    Detect if user explicitly asked to switch language (e.g. 'Tamil la pesunga' or 'Telugu lo matladandi').
    Returns the target language code or the current language code.
    """
    t = user_text.lower()
    if any(k in t for k in ["telugu", "தெலுங்கு", "తెలుగు"]):
        return "te"
    if any(k in t for k in ["tamil", "தமிழ்", "తమిళ"]):
        return "ta"
    return current_lang
